// Command gen generates the executors of the tablemode test server, as testdata/gqlgen.go
// does, with a plugin that changes the schema after gqlgen loads it, as a SchemaMutator
// may, and one that generates code calling the marshalers and unmarshalers of the
// generated package by their names. The code is generated for the changed schema, while
// the executors validate requests against the schema of the sources, which the changes
// are not in. Like gqlgen,
// it generates in table mode when it is built with the gqlgen_table tag, with which the
// table packages run it.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/vektah/gqlparser/v2/ast"

	"github.com/99designs/gqlgen/api"
	"github.com/99designs/gqlgen/codegen"
	"github.com/99designs/gqlgen/codegen/config"
	"github.com/99designs/gqlgen/plugin"
)

func main() {
	cfgPath := flag.String("config", "", "path to config file")
	flag.Parse()

	log.SetOutput(io.Discard)
	start := time.Now()

	cfg, err := config.LoadConfig(*cfgPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "failed to load config", err.Error())
		os.Exit(2)
	}
	if err := api.Generate(cfg, api.AddPlugin(guard{}), api.AddPlugin(callers{})); err != nil {
		fmt.Fprintln(os.Stderr, err.Error())
		os.Exit(3)
	}
	fmt.Printf("Generated %s in %4.2fs\n", cfg.Exec.ImportPath(), time.Since(start).Seconds())
}

// guard changes the fields of the query type that a schema of the tablemode test server
// declares for it: it puts @auth on pluginGuarded and @trimArg on the argument of
// pluginTrimmed, makes pluginRequired non-null, removes pluginRemoved, and puts directives
// where their definitions do not allow them: @trimArg, which the schema declares on
// arguments only, on pluginMisplaced, @onObject and @onInput on pluginObjectOnField and
// pluginInputObjectOnField, @onField on the scalar Tagged and @onObject on MarkInput.v.
type guard struct{}

var _ plugin.SchemaMutator = guard{}

func (guard) Name() string { return "guard" }

func (guard) MutateSchema(s *ast.Schema) error {
	fields := s.Query.Fields
	if f := fields.ForName("pluginGuarded"); f != nil {
		f.Directives = append(f.Directives, directive(s, "auth", ast.LocationFieldDefinition))
	}
	if f := fields.ForName("pluginTrimmed"); f != nil {
		text := f.Arguments.ForName("text")
		text.Directives = append(text.Directives,
			directive(s, "trimArg", ast.LocationArgumentDefinition))
	}
	if f := fields.ForName("pluginRequired"); f != nil {
		f.Type = ast.NonNullNamedType(f.Type.Name(), nil)
	}
	if f := fields.ForName("pluginMisplaced"); f != nil {
		f.Directives = append(f.Directives, directive(s, "trimArg", ast.LocationFieldDefinition))
	}
	if f := fields.ForName("pluginObjectOnField"); f != nil {
		f.Directives = append(f.Directives, directive(s, "onObject", ast.LocationFieldDefinition))
	}
	if f := fields.ForName("pluginInputObjectOnField"); f != nil {
		f.Directives = append(f.Directives, directive(s, "onInput", ast.LocationFieldDefinition))
	}
	if typ := s.Types["Tagged"]; typ != nil {
		typ.Directives = append(typ.Directives, directive(s, "onField", ast.LocationScalar))
	}
	if typ := s.Types["MarkInput"]; typ != nil {
		v := typ.Fields.ForName("v")
		v.Directives = append(
			v.Directives,
			directive(s, "onObject", ast.LocationInputFieldDefinition),
		)
	}
	s.Query.Fields = slices.DeleteFunc(fields, func(f *ast.FieldDefinition) bool {
		return f.Name == "pluginRemoved"
	})
	return nil
}

// callers writes plugin_calls.go into the package of the executor of the schema with the
// type Human, as a plugin that generates code calling the marshalers and unmarshalers of
// the functions mode by their names would. Its PluginCalls unmarshals a raw value of each
// scalar and enum of the schema that is both an input and an output, and of their lists,
// and marshals the result, so that the tests compare the functions of those names that
// table mode generates with those of the functions mode.
type callers struct{}

var _ plugin.CodeGenerator = callers{}

func (callers) Name() string { return "callers" }

func (callers) GenerateCode(data *codegen.Data) error {
	if data.Objects.ByName("Human") == nil {
		return nil
	}
	var refs []*config.TypeReference
	for _, t := range data.ReferencedTypes {
		if t.MarshalFunc() != "" && t.UnmarshalFunc() != "" && rawValue(t) != "" {
			refs = append(refs, t)
		}
	}
	slices.SortFunc(refs, func(a, b *config.TypeReference) int {
		return strings.Compare(a.MarshalFunc(), b.MarshalFunc())
	})
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by the gen command of the tablemode test server. DO NOT EDIT.

package %s

import (
	"bytes"
	"context"
	"fmt"

	"github.com/99designs/gqlgen/graphql"
)

// PluginCalls unmarshals a raw value of each scalar and enum type reference and marshals
// the result, with the marshalers and unmarshalers that the generated package declares
// with the names of the functions mode.
func PluginCalls(ctx context.Context, schema graphql.ExecutableSchema) []string {
	ec := newExecutionContext(graphql.GetOperationContext(ctx), schema.(*executableSchema), nil)
	var res []string
`, data.Config.Exec.Package)
	ec, arg := data.ECDot(), data.ECArg()
	for _, t := range refs {
		unmarshal := ec + t.UnmarshalFunc() + "(ctx, " + arg + rawValue(t) + ")"
		marshal := ec + t.MarshalFunc() + "(ctx, " + arg + "nil, v)"
		fmt.Fprintf(&b, "\t{\n\t\tv, err := %s\n", unmarshal)
		name := strconv.Quote(t.GQL.String())
		fmt.Fprintf(&b, "\t\tres = append(res, pluginResult(%s, %s, err))\n\t}\n", name, marshal)
	}
	b.WriteString(`	return res
}

func pluginResult(name string, m graphql.Marshaler, err error) string {
	var buf bytes.Buffer
	if m != nil {
		m.MarshalGQL(&buf)
	}
	return fmt.Sprintf("%s %s err=%v", name, buf.String(), err)
}
`)
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(data.Config.Exec.Dir(), "plugin_calls.go"), src, 0o644)
}

// rawValue returns the Go expression of a raw input value of t, a built-in scalar, an enum
// or a list of them, or "" for the other types and for Go types that unmarshal themselves,
// which may refuse any value.
func rawValue(t *config.TypeReference) string {
	if t.IsMarshaler {
		return ""
	}
	if t.IsSlice() {
		if elem := rawValue(t.Elem()); elem != "" {
			return "[]any{" + elem + "}"
		}
		return ""
	}
	switch def := t.Definition; {
	case def.Kind == ast.Enum && len(def.EnumValues) > 0:
		return fmt.Sprintf("%q", def.EnumValues[0].Name)
	case def.Name == "String" || def.Name == "ID":
		return `"x"`
	case def.Name == "Int":
		return "int64(7)"
	case def.Name == "Float":
		return "1.5"
	case def.Name == "Boolean":
		return "true"
	}
	return ""
}

// directive is the application of the directive called name, without arguments.
func directive(s *ast.Schema, name string, location ast.DirectiveLocation) *ast.Directive {
	return &ast.Directive{Name: name, Definition: s.Directives[name], Location: location}
}
